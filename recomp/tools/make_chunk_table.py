#!/usr/bin/env python3
"""Write the dispatcher's chunk table (sorted entry addresses) from DolRecomp's generated.h.

usage: make_chunk_table.py <generated.h> <chunks.inc> [prefix table]
  prefix/table name the functions and the array (default func_ / kChunks); the LLVM build also
  links the C chunks as cfunc_* in kCChunks.
"""
import re
import sys

prefix, table = (sys.argv[3], sys.argv[4]) if len(sys.argv) > 4 else ("func_", "kChunks")

addrs = sorted({int(m.group(1), 16) for m in re.finditer(r"^void func_([0-9A-F]{8})\(CPUState\* ctx\);", open(sys.argv[1]).read(), re.M)})
lines = ["/* generated by tools/make_chunk_table.py: chunk entry table */"]
lines += [f"void {prefix}{a:08X}(CPUState*);" for a in addrs]
lines.append(f"static const struct {{ u32 base; void (*fn)(CPUState*); }} {table}[] = {{")
lines += [f"    {{0x{a:08X}u, {prefix}{a:08X}}}," for a in addrs]
lines.append("};")
text = "\n".join(lines) + "\n"
try:
    if open(sys.argv[2]).read() == text:
        sys.exit(0)
except FileNotFoundError:
    pass
open(sys.argv[2], "w").write(text)
